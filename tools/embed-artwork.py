#!/usr/bin/env python3
"""Embed the scene artwork from images/ into sigenergy-flow-card.js.

Each image is cropped to its visible pixels and stored as lossless WebP, so the
card is a single self-contained file. Run after changing any of the images:

    python3 tools/embed-artwork.py
"""

import base64
import io
import pathlib
import re

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
CARD = ROOT / 'sigenergy-flow-card.js'
FILES = ['bg_villa_pv.png', 'ac_charger_bg.png', 'bg_sigenstor.png', 'bg_gateway.png']
BEGIN = '// BEGIN ARTWORK (generated by tools/embed-artwork.py)'
END = '// END ARTWORK'


def entry(name):
    image = Image.open(ROOT / 'images' / name).convert('RGBA')
    left, top, right, bottom = image.getchannel('A').getbbox()
    buffer = io.BytesIO()
    image.crop((left, top, right, bottom)).save(buffer, 'WEBP', lossless=True, method=6)
    data = base64.b64encode(buffer.getvalue()).decode('ascii')
    return (f"    '{name}': {{ size: [{image.width}, {image.height}], "
            f"crop: [{left}, {top}, {right - left}, {bottom - top}], "
            f"href: 'data:image/webp;base64,{data}' }},")


def main():
    block = '\n'.join([BEGIN, '// [size] is the source image, [crop] the visible region embedded as [href].',
                       'const ARTWORK = {', *map(entry, FILES), '};', END])
    source = CARD.read_text()
    pattern = re.compile(re.escape(BEGIN) + '.*?' + re.escape(END), re.S)
    if not pattern.search(source):
        raise SystemExit(f'{CARD.name}: artwork markers not found')
    CARD.write_text(pattern.sub(lambda _: block, source))
    print(f'{CARD.name}: {CARD.stat().st_size // 1024} KiB')


if __name__ == '__main__':
    main()
